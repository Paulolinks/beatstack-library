export type MessageKey = keyof (typeof messages)["en"];

export function isLocale(value: string): value is Locale {
  return value === "pt" || value === "en" || value === "es";
}

export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.en[key];
}

export function pickLocalized(
  locale: Locale,
  pt: string,
  en?: string | null,
  es?: string | null,
): string {
  if (locale === "en") return en?.trim() || pt;
  if (locale === "es") return es?.trim() || en?.trim() || pt;
  return pt;
}

export function pickOptionLabel(
  locale: Locale,
  option: { label: string; labelEn?: string; labelEs?: string },
): string {
  return pickLocalized(locale, option.label, option.labelEn, option.labelEs);
}

export function nextLocale(current: Locale): Locale {
  if (current === "en") return "pt";
  if (current === "pt") return "es";
  return "en";
}

export function localeLabel(locale: Locale): string {
  if (locale === "en") return "EN";
  if (locale === "pt") return "PT";
  return "ES";
}
